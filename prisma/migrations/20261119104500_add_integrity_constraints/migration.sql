-- Posted journals are immutable; corrections are reversals only.
CREATE OR REPLACE FUNCTION bakery_guard_journal() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'Journal records cannot be deleted'; END IF;
  IF TG_OP = 'UPDATE' AND TG_TABLE_NAME = 'journal_lines' THEN RAISE EXCEPTION 'Journal lines cannot be edited; post a reversal'; END IF;
  IF TG_OP = 'UPDATE' AND TG_TABLE_NAME = 'journal_entries' THEN
    IF OLD."entryNumber" IS DISTINCT FROM NEW."entryNumber" OR OLD."date" IS DISTINCT FROM NEW."date" OR OLD."description" IS DISTINCT FROM NEW."description" OR OLD."referenceType" IS DISTINCT FROM NEW."referenceType" OR OLD."referenceId" IS DISTINCT FROM NEW."referenceId" OR OLD."branchId" IS DISTINCT FROM NEW."branchId" OR OLD."createdById" IS DISTINCT FROM NEW."createdById" THEN
      RAISE EXCEPTION 'Posted journal headers cannot be edited'; END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER "journal_entries_immutable" BEFORE UPDATE OR DELETE ON "journal_entries" FOR EACH ROW EXECUTE FUNCTION bakery_guard_journal();
CREATE TRIGGER "journal_lines_immutable" BEFORE UPDATE OR DELETE ON "journal_lines" FOR EACH ROW EXECUTE FUNCTION bakery_guard_journal();
