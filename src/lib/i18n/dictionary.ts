const dictionaries: Record<Locale, Record<string, string>> = { en, ar };

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  let text = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
  }
  return text;
}

export function numericLocale(locale: Locale): string {
  return locale === "ar" ? "ar-YE-u-nu-latn" : "en-US";
}

const currencySymbols: Record<string, { ar: string; en: string }> = {
  YER: { ar: "ر.ي.", en: "YER" },
  SAR: { ar: "ر.س.", en: "SAR" },
  AED: { ar: "د.إ.", en: "AED" },
  EGP: { ar: "ج.م.", en: "EGP" },
  IQD: { ar: "د.ع.", en: "IQD" },
  KWD: { ar: "د.ك.", en: "KWD" },
  OMR: { ar: "ر.ع.", en: "OMR" },
  USD: { ar: "$", en: "$" },
  EUR: { ar: "€", en: "€" },
  GBP: { ar: "£", en: "£" },
};

export function formatMoney(value: number | string, locale: Locale, currency: string, dp = 2): string {
  const n = typeof value === "string" ? Number(value) : value;
  const formatted = formatNumber(Number.isFinite(n) ? n : 0, locale, dp);
  const code = currency.toUpperCase();
  const symbol = currencySymbols[code]?.[locale] ?? code;
  return locale === "ar" ? `${formatted}\u00a0${symbol}` : `${symbol}\u00a0${formatted}`;
}

export function formatDate(value: Date | string, locale: Locale, withTime = false): string {
  const d = typeof value === "string" ? new Date(value) : value;
  return new Intl.DateTimeFormat(numericLocale(locale), {
    numberingSystem: "latn",
    year: "numeric", month: "short", day: "numeric",
    ...(withTime ? { hour: "2-digit", minute: "2-digit" } : {}),
  }).format(d);
}

export function formatNumber(value: number | string, locale: Locale, dp = 2): string {
  const n = typeof value === "string" ? Number(value) : value;
  return new Intl.NumberFormat(numericLocale(locale), {
    numberingSystem: "latn",
    minimumFractionDigits: dp, maximumFractionDigits: dp,
  }).format(Number.isFinite(n) ? n : 0);
}
